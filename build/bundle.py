"""Builds SigmaSpy V2 into a single self-contained Luau file.

Every library from /src, every template from /templates and every asset from
/assets is embedded, so the produced file needs no network access to this
repository at runtime.

Usage: python build/bundle.py [output path]
"""

from __future__ import annotations

import base64
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "SigmaSpyV2.luau"

MAIN = "src/Main.lua"
FRAME = "build/frame.lua"
INFO_MODULE = "src/lib/Info.lua"
INLINED = ("Info", "Files")
LIBRARIES = ("Info", "Process", "Hook", "Flags", "Ui", "Generation", "Communication")

INSERT_PLACEHOLDER = "--INSERT: @lib/{name}.lua"
COMPILE_PLACEHOLDER = '{{"base64", "COMPILE: @lib/{name}.lua"}}'
EMBED_ANCHOR = "Files:PushConfig(Configuration)"

LONG_BRACKET_LEVEL = "=="

HEADER_NOTE = """--// Single-file build: every /src library, /templates file and /assets file
--// is embedded below, so this script only fetches its external dependencies
--// (Dear-ReGui and Roblox-parser). Generated by build/bundle.py
"""

EMBED_PATCH = """--// Files embedded at build time; keeps this build self-contained
do
\tlocal SourceFiles = {
__SOURCES__
\t}
\tlocal BinaryFiles = {
__BINARIES__
\t}

\tlocal FetchFile = Files.GetFile

\tfunction Files:GetFile(Path: string, CustomAsset: boolean?): string?
\t\t--// Workspace mode must keep reading the user's own files
\t\tif self.UseWorkspace then
\t\t\treturn FetchFile(self, Path, CustomAsset)
\t\tend

\t\tlocal Content = SourceFiles[Path]
\t\tlocal Encoded = BinaryFiles[Path]

\t\t--// crypt may be missing on some executors, fall back to a request
\t\tif Encoded then
\t\t\tlocal Success, Decoded = pcall(function()
\t\t\t\treturn crypt.base64decode(Encoded)
\t\t\tend)
\t\t\tContent = Success and Decoded or nil
\t\tend

\t\tif not Content then
\t\t\treturn FetchFile(self, Path, CustomAsset)
\t\tend

\t\tif not CustomAsset then
\t\t\treturn Content
\t\tend

\t\tlocal LocalPath = self:MakePath(Path)
\t\tself:FileCheck(LocalPath, function()
\t\t\treturn Content
\t\tend)

\t\treturn self:LoadCustomasset(LocalPath)
\tend
end
"""


def read_source(relative_path: str) -> str:
    text = (ROOT / relative_path).read_text(encoding="utf-8")
    return text.replace("\r\n", "\n")


def long_string(text: str, what: str) -> str:
    closing = f"]{LONG_BRACKET_LEVEL}]"
    if closing in text:
        raise ValueError(f"{what} contains {closing} and cannot be embedded verbatim")
    return f"[{LONG_BRACKET_LEVEL}[\n{text}\n]{LONG_BRACKET_LEVEL}]"


def replace_once(content: str, needle: str, replacement: str, what: str) -> str:
    if content.count(needle) != 1:
        raise ValueError(f"expected exactly one {what} in {MAIN}, found {content.count(needle)}")
    return content.replace(needle, replacement)


def embed_patch() -> str:
    sources: list[str] = []
    for template in sorted((ROOT / "templates").glob("*.lua")):
        key = f"templates/{template.name}"
        value = long_string(read_source(key), key)
        sources.append(f'\t\t["{key}"] = {value},')

    binaries: list[str] = []
    for asset in sorted(path for path in (ROOT / "assets").iterdir() if path.is_file()):
        key = f"assets/{asset.name}"
        encoded = base64.b64encode(asset.read_bytes()).decode("ascii")
        binaries.append(f'\t\t["{key}"] = "{encoded}",')

    return EMBED_PATCH.replace("__SOURCES__", "\n".join(sources)).replace(
        "__BINARIES__", "\n".join(binaries)
    )


def read_info() -> dict[str, str]:
    """Parses the string fields of src/lib/Info.lua, the single source of identity."""
    source = read_source(INFO_MODULE)
    fields = dict(re.findall(r'^\s*(\w+)\s*=\s*"([^"]*)"\s*,?\s*$', source, re.MULTILINE))

    missing = [key for key in ("Name", "Version", "Author") if not fields.get(key)]
    if missing:
        raise ValueError(f"{INFO_MODULE} is missing required fields: {', '.join(missing)}")

    return fields


def render_frame(info: dict[str, str]) -> str:
    """Substitutes {name}/{version}/{author}/... in build/frame.lua.

    Lookup is case-insensitive, and an all-caps placeholder uppercases the
    value, so {NAME} can be used where the banner wants shouting. Every
    Info.lua field is available, not just the required ones.
    """
    frame = read_source(FRAME)
    by_lowercase = {key.lower(): value for key, value in info.items()}

    def substitute(match: re.Match[str]) -> str:
        key = match.group(1)
        value = by_lowercase.get(key.lower())
        if value is None:
            known = ", ".join(sorted(info))
            raise ValueError(
                f"{FRAME} uses {{{key}}}, which {INFO_MODULE} does not define (known: {known})"
            )
        return value.upper() if key.isupper() else value

    return re.sub(r"\{(\w+)\}", substitute, frame)


def build() -> str:
    info = read_info()
    main = read_source(MAIN)

    for name in INLINED:
        path = f"src/lib/{name}.lua"
        main = replace_once(
            main,
            INSERT_PLACEHOLDER.format(name=name),
            read_source(path),
            f"{name}.lua insert placeholder",
        )

    for name in LIBRARIES:
        path = f"src/lib/{name}.lua"
        main = replace_once(
            main,
            COMPILE_PLACEHOLDER.format(name=name),
            long_string(read_source(path), path),
            f"{name}.lua compile placeholder",
        )

    main = replace_once(main, EMBED_ANCHOR, f"{embed_patch()}\n{EMBED_ANCHOR}", "embed anchor")

    for marker in ("COMPILE:", "INSERT:"):
        if marker in main:
            raise ValueError(f"unresolved {marker} directive left in the bundle")

    return f"{render_frame(info)}\n{HEADER_NOTE}\n{main}"


def main() -> None:
    output = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else DEFAULT_OUTPUT
    bundle = build()

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(bundle, encoding="utf-8", newline="\n")

    print(f"{output} - {len(bundle.encode('utf-8')):,} bytes, {bundle.count(chr(10)) + 1:,} lines")


if __name__ == "__main__":
    main()
